-- an existing view requires explicit review rather than silent replacement.
USE ROLE KUMO_DEMO_OWNER;
USE SECONDARY ROLES NONE;
CREATE SEMANTIC VIEW KUMO_SEMANTIC_DEMO.SEMANTIC.RETAIL_CUSTOMER_360
TABLES (
  CUSTOMERS AS KUMO_SEMANTIC_DEMO.GOVERNED.CUSTOMERS PRIMARY KEY (CUSTOMER_ID),
  ORDERS AS KUMO_SEMANTIC_DEMO.GOVERNED.ORDERS PRIMARY KEY (ORDER_ID),
  ORDER_ITEMS AS KUMO_SEMANTIC_DEMO.GOVERNED.ORDER_ITEMS PRIMARY KEY (ITEM_ID),
  PRODUCTS AS KUMO_SEMANTIC_DEMO.GOVERNED.PRODUCTS PRIMARY KEY (PRODUCT_ID)
)
RELATIONSHIPS (
  ORDERS_TO_CUSTOMERS AS ORDERS (CUSTOMER_ID) REFERENCES CUSTOMERS (CUSTOMER_ID),
  ITEMS_TO_ORDERS AS ORDER_ITEMS (ORDER_ID) REFERENCES ORDERS (ORDER_ID),
  ITEMS_TO_PRODUCTS AS ORDER_ITEMS (PRODUCT_ID) REFERENCES PRODUCTS (PRODUCT_ID)
)
FACTS (
  ORDERS.ORDER_TOTAL AS ORDER_TOTAL,
  ORDER_ITEMS.QUANTITY AS QUANTITY,
  ORDER_ITEMS.UNIT_PRICE AS UNIT_PRICE,
  ORDER_ITEMS.LINE_TOTAL AS LINE_TOTAL,
  PRODUCTS.LIST_PRICE AS LIST_PRICE
)
DIMENSIONS (
  CUSTOMERS.CUSTOMER_ID AS CUSTOMER_ID,
  CUSTOMERS.REGION AS REGION,
  CUSTOMERS.ACQUISITION_CHANNEL AS ACQUISITION_CHANNEL,
  CUSTOMERS.JOINED_AT AS JOINED_AT,
  ORDERS.ORDER_ID AS ORDER_ID,
  ORDERS.CUSTOMER_ID AS CUSTOMER_ID,
  ORDERS.ORDERED_AT AS ORDERED_AT,
  ORDERS.CHANNEL AS CHANNEL,
  ORDER_ITEMS.ITEM_ID AS ITEM_ID,
  ORDER_ITEMS.ORDER_ID AS ORDER_ID,
  ORDER_ITEMS.PRODUCT_ID AS PRODUCT_ID,
  ORDER_ITEMS.ORDERED_AT AS ORDERED_AT,
  PRODUCTS.PRODUCT_ID AS PRODUCT_ID,
  PRODUCTS.CATEGORY AS CATEGORY
)
METRICS (
  CUSTOMERS.CUSTOMER_COUNT AS COUNT(CUSTOMER_ID),
  ORDERS.ORDER_COUNT AS COUNT(ORDER_ID),
  ORDERS.SALES AS SUM(ORDER_TOTAL),
  ORDERS.AVERAGE_ORDER_VALUE AS AVG(ORDER_TOTAL),
  ORDER_ITEMS.ITEM_SALES AS SUM(LINE_TOTAL)
)
COMMENT = 'Synthetic retail; sql-v2; direct columns and single-column equality relationships only';
