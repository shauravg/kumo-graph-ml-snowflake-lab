CREATE TAG IF NOT EXISTS KUMO_SEMANTIC_DEMO.RAW.SENSITIVITY
  ALLOWED_VALUES 'SYNTHETIC_IDENTITY', 'SYNTHETIC_BEHAVIOR';
CREATE MASKING POLICY IF NOT EXISTS KUMO_SEMANTIC_DEMO.RAW.IDENTITY_STRING_MASK
  AS (VAL STRING) RETURNS STRING ->
  CASE WHEN IS_ROLE_IN_SESSION('KUMO_DEMO_IDENTITY_STEWARD') THEN VAL ELSE NULL END
  COMMENT = 'Defense in depth for fictional identity fields; ML inputs omit them entirely.';

CREATE TABLE IF NOT EXISTS KUMO_SEMANTIC_DEMO.RAW.CUSTOMERS (
  CUSTOMER_ID NUMBER(38,0) NOT NULL, REGION VARCHAR, ACQUISITION_CHANNEL VARCHAR,
  JOINED_AT TIMESTAMP_NTZ, ML_ELIGIBLE BOOLEAN NOT NULL);
CREATE TABLE IF NOT EXISTS KUMO_SEMANTIC_DEMO.RAW.CUSTOMER_IDENTITY (
  CUSTOMER_ID NUMBER(38,0) NOT NULL,
  FULL_NAME VARCHAR WITH MASKING POLICY KUMO_SEMANTIC_DEMO.RAW.IDENTITY_STRING_MASK
    WITH TAG (KUMO_SEMANTIC_DEMO.RAW.SENSITIVITY = 'SYNTHETIC_IDENTITY'),
  EMAIL VARCHAR WITH MASKING POLICY KUMO_SEMANTIC_DEMO.RAW.IDENTITY_STRING_MASK
    WITH TAG (KUMO_SEMANTIC_DEMO.RAW.SENSITIVITY = 'SYNTHETIC_IDENTITY'));
CREATE TABLE IF NOT EXISTS KUMO_SEMANTIC_DEMO.RAW.PRODUCTS (
  PRODUCT_ID NUMBER(38,0) NOT NULL, CATEGORY VARCHAR, LIST_PRICE NUMBER(12,2));
CREATE TABLE IF NOT EXISTS KUMO_SEMANTIC_DEMO.RAW.ORDERS (
  ORDER_ID NUMBER(38,0) NOT NULL, CUSTOMER_ID NUMBER(38,0) NOT NULL,
  ORDERED_AT TIMESTAMP_NTZ, CHANNEL VARCHAR, ORDER_TOTAL NUMBER(12,2));
CREATE TABLE IF NOT EXISTS KUMO_SEMANTIC_DEMO.RAW.ORDER_ITEMS (
  ITEM_ID NUMBER(38,0) NOT NULL, ORDER_ID NUMBER(38,0) NOT NULL,
  PRODUCT_ID NUMBER(38,0) NOT NULL, ORDERED_AT TIMESTAMP_NTZ,
  QUANTITY NUMBER(38,0), UNIT_PRICE NUMBER(12,2), LINE_TOTAL NUMBER(12,2));

CREATE SECURE VIEW IF NOT EXISTS KUMO_SEMANTIC_DEMO.GOVERNED.CUSTOMERS AS
SELECT CUSTOMER_ID, REGION, ACQUISITION_CHANNEL, JOINED_AT
FROM KUMO_SEMANTIC_DEMO.RAW.CUSTOMERS WHERE ML_ELIGIBLE = TRUE;
CREATE SECURE VIEW IF NOT EXISTS KUMO_SEMANTIC_DEMO.GOVERNED.ORDERS AS
SELECT O.ORDER_ID, O.CUSTOMER_ID, O.ORDERED_AT, O.CHANNEL, O.ORDER_TOTAL
FROM KUMO_SEMANTIC_DEMO.RAW.ORDERS O
JOIN KUMO_SEMANTIC_DEMO.RAW.CUSTOMERS C ON C.CUSTOMER_ID = O.CUSTOMER_ID
WHERE C.ML_ELIGIBLE = TRUE;
CREATE SECURE VIEW IF NOT EXISTS KUMO_SEMANTIC_DEMO.GOVERNED.ORDER_ITEMS AS
SELECT I.ITEM_ID, I.ORDER_ID, I.PRODUCT_ID, I.ORDERED_AT, I.QUANTITY, I.UNIT_PRICE, I.LINE_TOTAL
FROM KUMO_SEMANTIC_DEMO.RAW.ORDER_ITEMS I
JOIN KUMO_SEMANTIC_DEMO.RAW.ORDERS O ON I.ORDER_ID = O.ORDER_ID
JOIN KUMO_SEMANTIC_DEMO.RAW.CUSTOMERS C ON C.CUSTOMER_ID = O.CUSTOMER_ID
WHERE C.ML_ELIGIBLE = TRUE;
CREATE SECURE VIEW IF NOT EXISTS KUMO_SEMANTIC_DEMO.GOVERNED.PRODUCTS AS
SELECT PRODUCT_ID, CATEGORY, LIST_PRICE FROM KUMO_SEMANTIC_DEMO.RAW.PRODUCTS;

